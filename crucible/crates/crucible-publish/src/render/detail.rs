/// Which currency an IPC-5 board is scored in, and what its cell says when
/// nothing scores.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Ipc5Scoring {
    /// Plan LENGTH against the vendored archive field's lengths.
    Length,
    /// MAKESPAN against the archive field's, computed per `.soln` from the
    /// timed steps. Scored only on rows carrying the 0.22 makespan column.
    Makespan,
    /// Nothing to score against: the cell is its fixed note.
    Coverage,
}

