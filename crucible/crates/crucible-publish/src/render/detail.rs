/// How a modern board's quality cell is produced.
#[derive(Debug, Clone, Copy)]
enum ModernQuality {
    /// Scored against the official best-known bounds file. `year_key` is
    /// TRACK-SCOPED (`"2023-agl"`, `"2023-sat"`), never a bare year: agl/, sat/
    /// and opt/ carry different instance sets under the same domain names, so a
    /// bare-year key would join a bound from one track onto an instance from
    /// another. When nothing scores, the cell is `"coverage-only"`.
    Bounds {
        year_key: &'static str,
        suffix: &'static str,
    },
    /// A fixed note -- the board has no scorable currency held here.
    Fixed(&'static str),
}

