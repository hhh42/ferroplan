//! `benchmarks/ipc-standings.md` -- the one-table-per-competition reference.
//! Port of `benchmarks/standings.py`'s `main()` (:761-1098).
//!
//! This is the document that says, for every board we hold, what was entered,
//! what it covered, in what currency it was scored, and how each unsolved row
//! failed. Five columns of prose, correct and unreadable at a glance -- which
//! is why `STANDINGS.md` exists beside it.
//!
//! Three things in here are incidents rather than layout, and each has its own
//! comment at the site:
//!
//! * **`seq-sat`, `tempo-sat` and `seq-opt` each appear TWICE**, once under
//!   IPC-6 and once under IPC-7, from ONE raw split on each row's own `ipc`
//!   field. The sweep is shared; the competitions are not.
//! * **An absent board renders one of two texts**, and they make opposite
//!   claims about the record -- see [`RenderCtx::absent_cell`].
//! * **The mco rows render their quality note even when absent.** The
//!   wall-clock rule is a DECISION, taken in 0.16 and re-affirmed for the 0.23
//!   re-entry, and it must be readable before the sweep lands rather than only
//!   after. Every other absent row renders em-dashes across.
//!
//! ## The prose belongs in the manifest
//!
//! The `const` tables below hold the document's SKELETON: section headings,
//! the column list, each board's `entered` text and each board's fixed quality
//! note. None of it is logic -- it is editorial copy about boards, and the
//! manifest (`benchmarks/manifest.toml`) is where facts about boards live.
//! `[[board]]` does not carry these fields yet, so they are here, in one place,
//! marked, so that moving them is a mechanical change with nothing to decide.
//! Until then: **a new board needs an entry in this file as well as the
//! manifest**, and a board missing from the render lists below cannot appear in
//! the table however completely it was swept -- 0.20 added `ipc2026-numeric` to
//! `SWEEPS` and not to the render list, and it was invisible for a cycle.

