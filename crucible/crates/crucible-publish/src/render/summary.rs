//! `STANDINGS.md` -- the at-a-glance view. Port of `write_summary` (:583-701).
//!
//! `ipc-standings.md` is the reference table: every track, every failure class,
//! five columns of prose. Correct, and useless for the question "roughly where
//! are we?". This answers that question and links there for the detail.
//!
//! Three rules here are incidents, not layout.
//!
//! **The delta column obeys one law: a snapshot is only compared against a
//! predecessor measured on the SAME BOX.** Faster silicon inflates coverage at
//! a fixed budget, so a cloud-to-Air "improvement" would be pure hardware.
//! Where no comparable predecessor exists the column says so instead of
//! inventing a number. The law is enforced by the type -- the only way to hold
//! a comparable predecessor is [`History::comparable_predecessor`], which is
//! also where the second half lives: the PREVIOUS RELEASE by version, never the
//! most recently MEASURED snapshot. A backfilled old tag is measured late (0.19
//! was re-swept after 0.20 shipped), and picking by date silently compares a
//! release to its grandparent. On 2018-sat that is the difference between +7
//! and +17.
//!
//! **The buckets sort by percentage DESCENDING with a STABLE sort.** Ties keep
//! manifest order, so two boards that land on the same share cannot swap places
//! between runs. `sort_by`, never `sort_unstable_by` -- a reordered pair is a
//! diff in a published table with no number wrong to point at.
//!
//! **Cloud-era boards are excluded from the headline total.** They are not
//! comparable to the boards above them; averaging the two would launder a
//! hardware change into a result. They get their own section saying exactly
//! that, because dropping them silently would claim we never measured them.
//!
//! Section prose and the bucket thresholds below belong in
//! `benchmarks/manifest.toml` beside the boards they describe; see the note on
//! `BANDS` and the module header of [`super::detail`].
//!
//! [`History::comparable_predecessor`]: crate::history::History::comparable_predecessor

use crate::fmt::{self, glyph};
use crate::history::delta_cell;
use crate::render::RenderCtx;

// ===========================================================================
// THE SKELETON -- belongs in benchmarks/manifest.toml; see the module header.
